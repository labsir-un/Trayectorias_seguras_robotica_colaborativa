"""
Head pose estimator for colab_supervision_operator.

This module contains the domain logic used to estimate the
orientation of the operator's head from facial landmarks.
"""

from dataclasses import dataclass
from typing import Optional

import cv2
import numpy as np


@dataclass
class HeadPoseResult:
    """
    Complete result generated by HeadPoseEstimator.
    """

    yaw: float
    pitch: float
    roll: float

    pose_valid: bool


class HeadPoseEstimator():
    """
    Estimate operator head orientation from facial landmarks.

    The estimator calculates the three rotational components
    of the head:

        yaw:
            Horizontal rotation of the head.

        pitch:
            Vertical rotation of the head.

        roll:
            Rotation of the head around the longitudinal axis.

    Angles are expressed in degrees.
    """

    def __init__(self,
        camera_matrix: Optional[np.ndarray] = None,
        distortion_coefficients: Optional[np.ndarray] = None) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._camera_matrix = camera_matrix
        self._distortion_coefficients = distortion_coefficients

        # --------------------------------------------------
        # Current observations
        # --------------------------------------------------

        self._yaw = 0.0
        self._pitch = 0.0
        self._roll = 0.0
        self._pose_valid = False

    # ======================================================
    # UPDATE
    # ======================================================

    def update(self, image_points: np.ndarray, image_size: tuple[int, int]) -> HeadPoseResult:
        """
        Update the head-pose estimator with new facial
        landmark coordinates.

        Args:
            image_points:
                2D facial landmark coordinates.

            image_size:
                Image dimensions as (width, height).

        Returns:
            Updated HeadPoseResult.
        """

        self._validate_observations(image_points, image_size)

        # --------------------------------------------------
        # Camera parameters
        # --------------------------------------------------

        camera_matrix = self._get_camera_matrix(image_size)

        distortion_coefficients = self._get_distortion_coefficients()

        # --------------------------------------------------
        # Reference 3D facial model
        # --------------------------------------------------

        model_points = self._get_model_points()

        # --------------------------------------------------
        # Estimate head pose
        # --------------------------------------------------

        success, rotation_vector, _ = cv2.solvePnP(
            model_points,
            image_points,
            camera_matrix,
            distortion_coefficients,
            flags=cv2.SOLVEPNP_ITERATIVE
        )

        if not success:
            self._pose_valid = False
            return self.get_result()

        # --------------------------------------------------
        # Rotation vector -> rotation matrix
        # --------------------------------------------------

        rotation_matrix, _ = cv2.Rodrigues(rotation_vector)

        # --------------------------------------------------
        # Rotation matrix -> Euler angles
        # --------------------------------------------------

        self._yaw, self._pitch, self._roll = (self._rotation_matrix_to_euler(rotation_matrix))
        self._pose_valid = True

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_camera_matrix(self, camera_matrix: np.ndarray) -> None:
        """
        Set the camera intrinsic matrix.
        """
        self._validate_camera_matrix(camera_matrix)
        self._camera_matrix = camera_matrix

    def set_distortion_coefficients(self, distortion_coefficients: np.ndarray) -> None:
        """
        Set the camera distortion coefficients.
        """

        if not isinstance(distortion_coefficients, np.ndarray):
            raise TypeError("distortion_coefficients must be a numpy array")

        self._distortion_coefficients = distortion_coefficients

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_camera_matrix(self) -> Optional[np.ndarray]:

        if self._camera_matrix is None:
            return None

        return self._camera_matrix.copy()

    def get_distortion_coefficients(self) -> Optional[np.ndarray]:

        if self._distortion_coefficients is None:
            return None

        return self._distortion_coefficients.copy()

    # ======================================================
    # GETTERS - ATOMIC OBSERVATIONS
    # ======================================================

    def get_yaw(self) -> float:
        return self._yaw

    def get_pitch(self) -> float:
        return self._pitch

    def get_roll(self) -> float:
        return self._roll

    def is_pose_valid(self) -> bool:
        return self._pose_valid

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_result(self) -> HeadPoseResult:
        """
        Return the complete current head-pose result.
        """

        return HeadPoseResult(
            yaw=self._yaw,
            pitch=self._pitch,
            roll=self._roll,
            pose_valid=self._pose_valid
        )

    # ======================================================
    # INTERNAL METHODS
    # ======================================================

    @staticmethod
    def _get_model_points() -> np.ndarray:
        """
        Return the reference 3D facial model.

        The points correspond to:

            0 -> nose
            1 -> chin
            2 -> left eye
            3 -> right eye
            4 -> left mouth corner
            5 -> right mouth corner
        """
        model_points = np.array(
            [
                (0.0, 0.0, 0.0),            # Nose
                (0.0, -63.6, -12.5),         # Chin
                (-43.3, 32.7, -26.0),        # Left eye
                (43.3, 32.7, -26.0),         # Right eye
                (-28.9, -28.9, -24.1),       # Left mouth
                (28.9, -28.9, -24.1),        # Right mouth
            ],
            dtype=np.float64
        )

        return model_points

    def _get_camera_matrix(self, image_size: tuple[int, int]) -> np.ndarray:
        """
        Return the camera intrinsic matrix.

        If no calibrated camera matrix is provided, an
        approximate matrix is generated from the image size.
        """

        if self._camera_matrix is not None:
            return self._camera_matrix

        width, height = image_size
        focal_length = width
        center = (width / 2.0, height / 2.0)

        camera_matrix = np.array(
            [
                [
                    focal_length,
                    0.0,
                    center[0]
                ],
                [
                    0.0,
                    focal_length,
                    center[1]
                ],
                [
                    0.0,
                    0.0,
                    1.0
                ]
            ],
            dtype=np.float64
        )

        return camera_matrix

    def _get_distortion_coefficients(self) -> np.ndarray:
        """
        Return camera distortion coefficients.
        """

        if self._distortion_coefficients is None:
            return np.zeros((4, 1), dtype=np.float64)

        return self._distortion_coefficients

    @staticmethod
    def _rotation_matrix_to_euler(rotation_matrix: np.ndarray) -> tuple[float, float, float]:

        """
        Convert a rotation matrix into yaw, pitch and roll
        angles in degrees.
        """

        sy = np.sqrt(rotation_matrix[0, 0] ** 2 + rotation_matrix[1, 0] ** 2)
        singular = sy < 1e-6

        if not singular:

            x = np.arctan2(rotation_matrix[2, 1], rotation_matrix[2, 2])
            y = np.arctan2(-rotation_matrix[2, 0], sy)
            z = np.arctan2(rotation_matrix[1, 0], rotation_matrix[0, 0])

        else:
            x = np.arctan2(-rotation_matrix[1, 2], rotation_matrix[1, 1])
            y = np.arctan2(-rotation_matrix[2, 0],sy)
            z = 0.0

        roll = np.degrees(x)
        pitch = np.degrees(y)
        yaw = np.degrees(z)

        return yaw, pitch, roll

    # ======================================================
    # VALIDATION
    # ======================================================

    @staticmethod
    def _validate_camera_matrix(camera_matrix: np.ndarray) -> None:

        if not isinstance(camera_matrix, np.ndarray):
            raise TypeError("camera_matrix must be a numpy array")

        if camera_matrix.shape != (3, 3):
            raise ValueError("camera_matrix must have shape (3, 3)")

    @staticmethod
    def _validate_observations(image_points: np.ndarray, image_size: tuple[int, int]) -> None:

        if not isinstance(image_points, np.ndarray):
            raise TypeError("image_points must be a numpy array")

        if image_points.shape != (6, 2):
            raise ValueError("image_points must have shape (6, 2)")

        if len(image_size) != 2:
            raise ValueError("image_size must contain width and height")

        width, height = image_size

        if width <= 0 or height <= 0:
            raise ValueError("image dimensions must be greater than zero")