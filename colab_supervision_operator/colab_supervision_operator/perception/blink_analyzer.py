"""
Blink analyzer for colab_supervision_operator.

This module contains the domain logic used to detect operator
blinks from previously extracted eye-openness measurements.
"""

from dataclasses import dataclass
from collections import deque
from typing import Optional


@dataclass
class BlinkResult:
    """
    Complete result generated by BlinkAnalyzer.
    """

    eye_openness: float

    eyes_closed: bool
    blink_detected: bool

    blink_duration: float
    blink_frequency: float

    total_blinks: int


class BlinkAnalyzer():
    """
    Analyze operator blinking from eye-openness measurements.

    The analyzer receives normalized eye-openness values and
    evaluates temporal changes to detect individual blinks and
    calculate blink frequency.

    Expected input:

        eye_openness:
            Normalized eye openness in the range [0.0, 1.0].

        timestamp:
            Observation timestamp in seconds.
    """

    def __init__(self, eye_closed_threshold: float = 0.30, minimum_blink_duration: float = 0.08, maximum_blink_duration: float = 0.80, frequency_window: float = 60.0) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._eye_closed_threshold = eye_closed_threshold
        self._minimum_blink_duration = minimum_blink_duration
        self._maximum_blink_duration = maximum_blink_duration
        self._frequency_window = frequency_window

        # --------------------------------------------------
        # Current observations
        # --------------------------------------------------

        self._eye_openness = 0.0
        self._eyes_closed = False

        # --------------------------------------------------
        # Temporal state
        # --------------------------------------------------

        self._eyes_closed_since: Optional[float] = None

        self._blink_duration = 0.0
        self._blink_detected = False

        # --------------------------------------------------
        # Blink history
        # --------------------------------------------------

        self._blink_timestamps: deque[float] = deque()
        self._blink_frequency = 0.0

    # ======================================================
    # UPDATE
    # ======================================================

    def update(self, eye_openness: float, timestamp: float) -> BlinkResult:
        """
        Update the analyzer with a new eye-openness
        observation.

        Args:
            eye_openness:
                Normalized eye openness [0.0, 1.0].

            timestamp:
                Observation timestamp in seconds.

        Returns:
            Updated BlinkResult.
        """

        self._validate_observations(eye_openness,timestamp)
        self._eye_openness = eye_openness

        # --------------------------------------------------
        # Reset event state
        # --------------------------------------------------

        self._blink_detected = False

        # --------------------------------------------------
        # Determine eye state
        # --------------------------------------------------

        eyes_closed = (self._eye_openness < self._eye_closed_threshold)

        # --------------------------------------------------
        # Detect transition OPEN -> CLOSED
        # --------------------------------------------------

        if eyes_closed and not self._eyes_closed:

            self._eyes_closed = True
            self._eyes_closed_since = timestamp
            self._blink_duration = 0.0

        # --------------------------------------------------
        # Eye remains CLOSED
        # --------------------------------------------------

        elif eyes_closed and self._eyes_closed:

            if self._eyes_closed_since is not None:
                self._blink_duration = timestamp - self._eyes_closed_since

        # --------------------------------------------------
        # Detect transition CLOSED -> OPEN
        # --------------------------------------------------

        elif not eyes_closed and self._eyes_closed:

            if self._eyes_closed_since is not None:
                self._blink_duration = timestamp - self._eyes_closed_since

                if (
                    self._minimum_blink_duration
                    <= self._blink_duration
                    <= self._maximum_blink_duration
                ):

                    self._blink_timestamps.append(timestamp)
                    self._blink_detected = True

            self._eyes_closed = False
            self._eyes_closed_since = None

        # --------------------------------------------------
        # Update frequency
        # --------------------------------------------------

        self._remove_old_blinks(timestamp)
        self._blink_frequency = self._calculate_blink_frequency()

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_eye_closed_threshold(self, threshold: float) -> None:
        """
        Set the eye-openness threshold used to determine
        whether the eyes are closed.
        """

        self._validate_range(threshold, 0.0, 1.0, "eye_closed_threshold")
        self._eye_closed_threshold = threshold

    def set_minimum_blink_duration(self, duration: float) -> None:
        """
        Set the minimum duration required to classify an
        eye-closure event as a blink.
        """

        if duration < 0.0:
            raise ValueError("minimum_blink_duration cannot be negative")

        if duration > self._maximum_blink_duration:
            raise ValueError("minimum_blink_duration cannot be greater than maximum_blink_duration")

        self._minimum_blink_duration = duration

    def set_maximum_blink_duration(self, duration: float) -> None:
        """
        Set the maximum duration allowed for a blink.
        """

        if duration <= 0.0:
            raise ValueError("maximum_blink_duration must be greater than zero")

        if duration < self._minimum_blink_duration:
            raise ValueError("maximum_blink_duration cannot be less than minimum_blink_duration")

        self._maximum_blink_duration = duration

    def set_frequency_window(self, window: float) -> None:
        """
        Set the temporal window used to calculate blink
        frequency.
        """

        if window <= 0.0:
            raise ValueError("frequency_window must be greater than zero")

        self._frequency_window = window

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_eye_closed_threshold(self) -> float:
        return self._eye_closed_threshold

    def get_minimum_blink_duration(self) -> float:
        return self._minimum_blink_duration

    def get_maximum_blink_duration(self) -> float:
        return self._maximum_blink_duration

    def get_frequency_window(self) -> float:
        return self._frequency_window

    # ======================================================
    # GETTERS - ATOMIC OBSERVATIONS
    # ======================================================

    def get_eye_openness(self) -> float:
        return self._eye_openness

    def are_eyes_closed(self) -> bool:
        return self._eyes_closed

    def get_blink_duration(self) -> float:
        return self._blink_duration

    def is_blink_detected(self) -> bool:
        return self._blink_detected

    def get_blink_frequency(self) -> float:
        return self._blink_frequency

    def get_total_blinks(self) -> int:
        return len(self._blink_timestamps)

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_result(self) -> BlinkResult:
        """
        Return the complete current blink result.
        """

        return BlinkResult(
            eye_openness=self._eye_openness,
            eyes_closed=self._eyes_closed,
            blink_detected=self._blink_detected,
            blink_duration=self._blink_duration,
            blink_frequency=self._blink_frequency,
            total_blinks=len(self._blink_timestamps)
        )

    # ======================================================
    # INTERNAL METHODS
    # ======================================================

    def _remove_old_blinks(self, timestamp: float) -> None:
        """
        Remove blink events outside the configured
        frequency window.
        """

        limit = timestamp - self._frequency_window

        while self._blink_timestamps and self._blink_timestamps[0] < limit:
            self._blink_timestamps.popleft()

    def _calculate_blink_frequency(self) -> float:
        """
        Calculate blink frequency in blinks per minute.
        """

        if self._frequency_window <= 0.0:
            return 0.0

        frequency = (len(self._blink_timestamps) / self._frequency_window * 60.0)

        return frequency

    # ======================================================
    # VALIDATION
    # ======================================================

    @staticmethod
    def _validate_range(value: float, minimum: float, maximum: float, name: str) -> None:

        if not minimum <= value <= maximum:
            raise ValueError(f"{name} must be between {minimum} and {maximum}")

    @staticmethod
    def _validate_observations(eye_openness: float, timestamp: float) -> None:

        if not 0.0 <= eye_openness <= 1.0:
            raise ValueError("eye_openness must be between 0.0 and 1.0")

        if timestamp < 0.0:
            raise ValueError("timestamp cannot be negative")