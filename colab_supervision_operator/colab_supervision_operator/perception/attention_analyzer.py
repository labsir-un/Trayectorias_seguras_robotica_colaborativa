"""
Attention analyzer for colab_supervision_operator.

This module contains the domain logic used to evaluate operator
attention from head orientation and predefined task targets.
"""

from dataclasses import dataclass
from typing import Optional


@dataclass
class AttentionResult:
    """
    Complete result generated by AttentionAnalyzer.
    """

    head_yaw: float
    head_pitch: float
    head_roll: float

    attention_target: str
    attention_score: float

    task_attention: bool
    hmi_attention: bool
    distracted: bool


class AttentionAnalyzer():
    """
    Analyze operator attention from head orientation.

    The analyzer receives head-pose measurements and determines
    whether the operator is oriented toward the task, the HMI,
    or another direction.

    Expected inputs:

        head_yaw:
            Horizontal head orientation in degrees.

        head_pitch:
            Vertical head orientation in degrees.

        head_roll:
            Head rotation around the longitudinal axis in degrees.
    """

    def __init__(self,
        task_yaw_range: tuple[float, float] = (-55.0, -35.0),
        task_pitch_range: tuple[float, float] = (-5.0, 35.0),
        hmi_yaw_range: tuple[float, float] = (-70.0, 30.0),
        hmi_pitch_range: tuple[float, float] = (-50.0, 30.0),
        attention_score_threshold: float = 0.50) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._task_yaw_range = task_yaw_range
        self._task_pitch_range = task_pitch_range

        self._hmi_yaw_range = hmi_yaw_range
        self._hmi_pitch_range = hmi_pitch_range

        self._attention_score_threshold = attention_score_threshold

        # --------------------------------------------------
        # Current observations
        # --------------------------------------------------

        self._head_yaw = 0.0
        self._head_pitch = 0.0
        self._head_roll = 0.0

        # --------------------------------------------------
        # Current evaluation
        # --------------------------------------------------

        self._attention_target = "UNKNOWN"
        self._attention_score = 0.0
        self._task_attention = False
        self._hmi_attention = False
        self._distracted = False

    # ======================================================
    # UPDATE
    # ======================================================

    def update(self, head_yaw: float, head_pitch: float, head_roll: float) -> AttentionResult:
        """
        Update the analyzer with a new head-pose observation.

        Args:
            head_yaw:
                Horizontal head orientation in degrees.

            head_pitch:
                Vertical head orientation in degrees.

            head_roll:
                Head rotation in degrees.

        Returns:
            Updated AttentionResult.
        """

        self._validate_observations(head_yaw, head_pitch, head_roll)

        self._head_yaw = head_yaw
        self._head_pitch = head_pitch
        self._head_roll = head_roll

        # --------------------------------------------------
        # Reset current evaluation
        # --------------------------------------------------

        self._task_attention = False
        self._hmi_attention = False
        self._distracted = False

        # --------------------------------------------------
        # Evaluate attention target
        # --------------------------------------------------

        task_attention = self._is_inside_target(
            self._head_yaw,
            self._head_pitch,
            self._task_yaw_range,
            self._task_pitch_range
        )

        hmi_attention = self._is_inside_target(
            self._head_yaw,
            self._head_pitch,
            self._hmi_yaw_range,
            self._hmi_pitch_range
        )

        # --------------------------------------------------
        # Determine target
        # --------------------------------------------------

        if task_attention:

            self._attention_target = "TASK"
            self._task_attention = True
            self._attention_score = (
                self._calculate_attention_score(
                    self._head_yaw,
                    self._head_pitch,
                    self._task_yaw_range,
                    self._task_pitch_range
                )
            )

        elif hmi_attention:

            self._attention_target = "HMI"
            self._hmi_attention = True
            self._attention_score = (
                self._calculate_attention_score(
                    self._head_yaw,
                    self._head_pitch,
                    self._hmi_yaw_range,
                    self._hmi_pitch_range
                )
            )

        else:

            self._attention_target = "OTHER"
            self._distracted = True
            self._attention_score = 0.0

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_task_yaw_range(self, yaw_range: tuple[float, float]) -> None:
        """
        Set the accepted yaw range for task attention.
        """

        self._validate_range_pair(yaw_range, "task_yaw_range")
        self._task_yaw_range = yaw_range

    def set_task_pitch_range(self, pitch_range: tuple[float, float]) -> None:
        """
        Set the accepted pitch range for task attention.
        """

        self._validate_range_pair(pitch_range, "task_pitch_range")
        self._task_pitch_range = pitch_range

    def set_hmi_yaw_range(self, yaw_range: tuple[float, float]) -> None:
        """
        Set the accepted yaw range for HMI attention.
        """

        self._validate_range_pair(yaw_range,"hmi_yaw_range")
        self._hmi_yaw_range = yaw_range

    def set_hmi_pitch_range(self, pitch_range: tuple[float, float]) -> None:
        """
        Set the accepted pitch range for HMI attention.
        """

        self._validate_range_pair(pitch_range, "hmi_pitch_range")
        self._hmi_pitch_range = pitch_range

    def set_attention_score_threshold(self,threshold: float) -> None:
        """
        Set the minimum score required to consider the
        operator attentive.
        """

        self._validate_range(threshold, 0.0, 1.0, "attention_score_threshold")
        self._attention_score_threshold = threshold

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_task_yaw_range(self) -> tuple[float, float]:
        return self._task_yaw_range

    def get_task_pitch_range(self) -> tuple[float, float]:
        return self._task_pitch_range

    def get_hmi_yaw_range(self) -> tuple[float, float]:
        return self._hmi_yaw_range

    def get_hmi_pitch_range(self) -> tuple[float, float]:
        return self._hmi_pitch_range

    def get_attention_score_threshold(self) -> float:
        return self._attention_score_threshold

    # ======================================================
    # GETTERS - ATOMIC OBSERVATIONS
    # ======================================================

    def get_head_yaw(self) -> float:
        return self._head_yaw

    def get_head_pitch(self) -> float:
        return self._head_pitch

    def get_head_roll(self) -> float:
        return self._head_roll

    # ======================================================
    # GETTERS - ATOMIC EVALUATION
    # ======================================================

    def get_attention_target(self) -> str:
        return self._attention_target

    def get_attention_score(self) -> float:
        return self._attention_score

    def is_task_attention(self) -> bool:
        return self._task_attention

    def is_hmi_attention(self) -> bool:
        return self._hmi_attention

    def is_distracted(self) -> bool:
        return self._distracted

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_result(self) -> AttentionResult:
        """
        Return the complete current attention result.
        """

        return AttentionResult(
            head_yaw=self._head_yaw,
            head_pitch=self._head_pitch,
            head_roll=self._head_roll,
            attention_target=self._attention_target,
            attention_score=self._attention_score,
            task_attention=self._task_attention,
            hmi_attention=self._hmi_attention,
            distracted=self._distracted
        )

    # ======================================================
    # INTERNAL METHODS
    # ======================================================

    @staticmethod
    def _is_inside_target(
        yaw: float,
        pitch: float,
        yaw_range: tuple[float, float],
        pitch_range: tuple[float, float]) -> bool:

        yaw_inside = (yaw_range[0] <= yaw <= yaw_range[1])
        pitch_inside = (pitch_range[0] <= pitch <= pitch_range[1])

        return yaw_inside and pitch_inside

    @staticmethod
    def _calculate_attention_score(
        yaw: float,
        pitch: float,
        yaw_range: tuple[float, float],
        pitch_range: tuple[float, float]) -> float:

        yaw_center = (yaw_range[0] + yaw_range[1]) / 2.0

        pitch_center = (pitch_range[0] + pitch_range[1]) / 2.0

        yaw_half_range = (yaw_range[1] - yaw_range[0]) / 2.0

        pitch_half_range = (pitch_range[1]- pitch_range[0]) / 2.0

        if yaw_half_range <= 0.0:
            yaw_score = 0.0
        else:
            yaw_score = max(0.0, 1.0 - abs(yaw - yaw_center) / yaw_half_range)

        if pitch_half_range <= 0.0:
            pitch_score = 0.0
        else:
            pitch_score = max(0.0, 1.0 - abs(pitch - pitch_center) / pitch_half_range)

        score = (yaw_score + pitch_score) / 2.0

        return max(0.0, min(score, 1.0))

    # ======================================================
    # VALIDATION
    # ======================================================

    @staticmethod
    def _validate_range(value: float, minimum: float, maximum: float, name: str) -> None:

        if not minimum <= value <= maximum:
            raise ValueError(f"{name} must be between {minimum} and {maximum}")

    @staticmethod
    def _validate_range_pair(value: tuple[float, float], name: str) -> None:

        if len(value) != 2:
            raise ValueError(f"{name} must contain exactly two values")

        if value[0] >= value[1]:
            raise ValueError(f"{name} minimum must be less than maximum")

    @staticmethod
    def _validate_observations(
        head_yaw: float,
        head_pitch: float,
        head_roll: float) -> None:

        values = {
            "head_yaw": head_yaw,
            "head_pitch": head_pitch,
            "head_roll": head_roll
        }

        for name, value in values.items():

            if not isinstance(value, (int, float)):
                raise TypeError(f"{name} must be a numeric value")