"""
Depth-based person detector for colab_supervision_operator.

This module contains the domain logic used to estimate the
3D position and velocity of the operator from depth observations.
"""

from dataclasses import dataclass
from typing import Optional

import numpy as np


@dataclass
class PersonDepthResult:
    """
    Complete result generated by DepthPersonDetector.
    """

    person_detected: bool

    position: Optional[np.ndarray]
    velocity: Optional[np.ndarray]

    distance: Optional[float]

    confidence: float

    detection_valid: bool


class DepthPersonDetector():
    """
    Detect and track the operator in 3D using depth information.

    The detector receives a 3D position obtained from the depth
    perception pipeline and estimates the operator velocity from
    consecutive observations.

    Position is expressed in meters.

    Velocity is expressed in meters per second.
    """

    def __init__(self,
        minimum_confidence: float = 0.50,
        maximum_detection_distance: float = 5.0) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._minimum_confidence = minimum_confidence
        self._maximum_detection_distance = maximum_detection_distance

        # --------------------------------------------------
        # Current observation
        # --------------------------------------------------

        self._person_detected = False
        self._position: Optional[np.ndarray] = None
        self._velocity: Optional[np.ndarray] = None
        self._distance: Optional[float] = None
        self._confidence = 0.0

        # --------------------------------------------------
        # Temporal information
        # --------------------------------------------------

        self._previous_position: Optional[np.ndarray] = None
        self._previous_timestamp: Optional[float] = None

        # --------------------------------------------------
        # State
        # --------------------------------------------------

        self._detection_valid = False

    # ======================================================
    # UPDATE
    # ======================================================

    def update(self, position: Optional[np.ndarray], confidence: float, timestamp: float) -> PersonDepthResult:
        """
        Update the detector with a new 3D person observation.

        Args:
            position:
                Operator position [x, y, z] in meters.

                If None, no person was detected.

            confidence:
                Detection confidence [0.0, 1.0].

            timestamp:
                Observation timestamp in seconds.

        Returns:
            Updated PersonDepthResult.
        """
        self._validate_observations(position, confidence, timestamp)

        # --------------------------------------------------
        # Reset current state
        # --------------------------------------------------

        self._person_detected = False
        self._detection_valid = False
        self._distance = None
        self._confidence = confidence

        # --------------------------------------------------
        # No person detected
        # --------------------------------------------------

        if position is None:
            self._position = None
            self._velocity = None
            self._previous_position = None
            self._previous_timestamp = None

            return self.get_result()

        # --------------------------------------------------
        # Check confidence
        # --------------------------------------------------

        if confidence < self._minimum_confidence:
            self._position = None
            self._velocity = None
            self._previous_position = None
            self._previous_timestamp = None

            return self.get_result()

        # --------------------------------------------------
        # Store position
        # --------------------------------------------------

        self._position = position.copy()
        self._distance = float(np.linalg.norm(self._position))

        # --------------------------------------------------
        # Check maximum detection distance
        # --------------------------------------------------

        if self._distance > self._maximum_detection_distance:

            self._position = None
            self._velocity = None
            self._previous_position = None
            self._previous_timestamp = None

            return self.get_result()

        self._person_detected = True

        # --------------------------------------------------
        # Calculate velocity
        # --------------------------------------------------

        self._velocity = self._calculate_velocity(timestamp)

        # --------------------------------------------------
        # Store temporal information
        # --------------------------------------------------

        self._previous_position = self._position.copy()
        self._previous_timestamp = timestamp
        self._detection_valid = True

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_minimum_confidence(self, confidence: float) -> None:
        """
        Set the minimum confidence required to accept a
        person detection.
        """
        self._validate_range(confidence, 0.0, 1.0,"minimum_confidence")
        self._minimum_confidence = confidence

    def set_maximum_detection_distance(self, distance: float) -> None:
        """
        Set the maximum distance at which a person detection
        is considered valid.
        """

        if distance <= 0.0:
            raise ValueError("maximum_detection_distance must be greater than zero")

        self._maximum_detection_distance = distance

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_minimum_confidence(self) -> float:
        return self._minimum_confidence

    def get_maximum_detection_distance(self) -> float:
        return self._maximum_detection_distance

    # ======================================================
    # GETTERS - ATOMIC OBSERVATIONS
    # ======================================================

    def is_person_detected(self) -> bool:
        return self._person_detected

    def get_position(self) -> Optional[np.ndarray]:

        if self._position is None:
            return None

        return self._position.copy()

    def get_velocity(self) -> Optional[np.ndarray]:

        if self._velocity is None:
            return None

        return self._velocity.copy()

    def get_distance(self) -> Optional[float]:
        return self._distance

    def get_confidence(self) -> float:
        return self._confidence

    def is_detection_valid(self) -> bool:
        return self._detection_valid

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_result(self) -> PersonDepthResult:
        """
        Return the complete current depth detection result.
        """
        return PersonDepthResult(
            person_detected = self._person_detected,
            position = None if self._position is None else self._position.copy(),
            velocity = None if self._velocity is None else self._velocity.copy(),
            distance = self._distance,
            confidence = self._confidence,
            detection_valid = self._detection_valid
        )

    # ======================================================
    # INTERNAL METHODS
    # ======================================================

    def _calculate_velocity(self, timestamp: float) -> Optional[np.ndarray]:
        """
        Calculate the operator velocity from consecutive
        3D position measurements.
        """

        if self._previous_position is None:
            return None

        if self._previous_timestamp is None:
            return None

        delta_time = timestamp - self._previous_timestamp

        if delta_time <= 0.0:
            return None

        displacement = self._position - self._previous_position
        velocity =  displacement / delta_time

        return velocity

    # ======================================================
    # VALIDATION
    # ======================================================

    @staticmethod
    def _validate_range(value: float, minimum: float, maximum: float,name: str) -> None:

        if not minimum <= value <= maximum:
            raise ValueError(f"{name} must be between {minimum} and {maximum}")

    @staticmethod
    def _validate_observations(position: Optional[np.ndarray], confidence: float, timestamp: float) -> None:

        if position is not None:

            if not isinstance(position,np.ndarray):
                raise TypeError("position must be a numpy array or None")

            if position.shape != (3,):
                raise ValueError("position must contain exactly three values")

            if not np.all(np.isfinite(position)):
                raise ValueError("position contains invalid values")

        if not 0.0 <= confidence <= 1.0:
            raise ValueError("confidence must be between 0.0 and 1.0")

        if timestamp < 0.0:
            raise ValueError("timestamp cannot be negative")