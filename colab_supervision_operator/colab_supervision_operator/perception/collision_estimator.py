"""
Collision estimator for colab_supervision_operator.

This module contains the domain logic used to estimate the
collision risk between the robot and the operator.
"""

from dataclasses import dataclass
from typing import Optional

import numpy as np


@dataclass
class CollisionResult:
    """
    Complete result generated by CollisionEstimator.
    """

    distance: float

    relative_velocity: float
    approach_velocity: float

    time_to_collision: Optional[float]

    collision_risk: str
    collision_risk_score: float

    collision_imminent: bool


class CollisionEstimator():
    """
    Estimate the collision risk between the robot and the operator.

    The estimator uses the relative position and velocity between
    the robot and the operator.

    Distances are expressed in meters and velocities in meters
    per second.
    """

    def __init__(self,
        warning_distance: float = 1.00,
        critical_distance: float = 0.50,
        warning_time_to_collision: float = 2.00,
        critical_time_to_collision: float = 1.00) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._warning_distance = warning_distance
        self._critical_distance = critical_distance
        self._warning_time_to_collision = warning_time_to_collision
        self._critical_time_to_collision = critical_time_to_collision

        # --------------------------------------------------
        # Current observations
        # --------------------------------------------------

        self._robot_position = np.zeros(3, dtype=float)
        self._robot_velocity = np.zeros(3, dtype=float)
        self._operator_position = np.zeros(3, dtype=float)
        self._operator_velocity = np.zeros(3, dtype=float)

        # --------------------------------------------------
        # Current evaluation
        # --------------------------------------------------

        self._distance = 0.0
        self._relative_velocity = 0.0
        self._approach_velocity = 0.0
        self._time_to_collision: Optional[float] = None
        self._collision_risk = "UNKNOWN"
        self._collision_risk_score = 0.0
        self._collision_imminent = False
        self._state_valid = False

    # ======================================================
    # UPDATE
    # ======================================================

    def update(self,
        robot_position: np.ndarray,
        robot_velocity: np.ndarray,
        operator_position: np.ndarray,
        operator_velocity: np.ndarray) -> CollisionResult:
        """
        Update the collision estimator with robot and operator
        states.

        Args:
            robot_position:
                Robot reference position [x, y, z] in meters.

            robot_velocity:
                Robot reference velocity [vx, vy, vz] in m/s.

            operator_position:
                Operator position [x, y, z] in meters.

            operator_velocity:
                Operator velocity [vx, vy, vz] in m/s.

        Returns:
            Updated CollisionResult.
        """

        self._validate_observations(
            robot_position,
            robot_velocity,
            operator_position,
            operator_velocity
        )

        self._robot_position =  robot_position.copy()
        self._robot_velocity = robot_velocity.copy()

        self._operator_position = operator_position.copy()
        self._operator_velocity = operator_velocity.copy()

        # --------------------------------------------------
        # Distance
        # --------------------------------------------------

        self._distance = self._calculate_distance()

        # --------------------------------------------------
        # Relative velocity
        # --------------------------------------------------

        relative_velocity_vector = self._operator_velocity - self._robot_velocity

        self._relative_velocity = np.linalg.norm(relative_velocity_vector)

        # --------------------------------------------------
        # Approach velocity
        # --------------------------------------------------

        self._approach_velocity = self._calculate_approach_velocity(relative_velocity_vector)


        # --------------------------------------------------
        # Time to collision
        # --------------------------------------------------

        self._time_to_collision = self._calculate_time_to_collision()

        # --------------------------------------------------
        # Collision risk
        # --------------------------------------------------

        self._collision_risk_score = self._calculate_collision_risk_score()
        self._collision_risk = self._calculate_collision_risk()
        self._collision_imminent = self._calculate_collision_imminent()
        self._state_valid = True

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_warning_distance(self, distance: float) -> None:
        """
        Set the distance at which the collision risk becomes
        significant.
        """

        if distance <= 0.0:
            raise ValueError("warning_distance must be greater than zero")

        if distance <= self._critical_distance:
            raise ValueError("warning_distance must be greater than critical_distance")

        self._warning_distance = distance

    def set_critical_distance(self, distance: float) -> None:
        """
        Set the critical collision distance.
        """

        if distance <= 0.0:
            raise ValueError("critical_distance must be greater than zero")

        if distance >= self._warning_distance:
            raise ValueError("critical_distance must be less than warning_distance")

        self._critical_distance = distance

    def set_warning_time_to_collision(self, time: float) -> None:
        """
        Set the warning time-to-collision threshold.
        """

        if time <= 0.0:
            raise ValueError("warning_time_to_collision must be greater than zero")

        if time <= self._critical_time_to_collision:
            raise ValueError("warning_time_to_collision must be greater than critical_time_to_collision")

        self._warning_time_to_collision = time

    def set_critical_time_to_collision(self, time: float) -> None:
        """
        Set the critical time-to-collision threshold.
        """

        if time <= 0.0:
            raise ValueError("critical_time_to_collision must be greater than zero")

        if time >= self._warning_time_to_collision:
            raise ValueError("critical_time_to_collision must be less than warning_time_to_collision")

        self._critical_time_to_collision = time

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_warning_distance(self) -> float:
        return self._warning_distance

    def get_critical_distance(self) -> float:
        return self._critical_distance

    def get_warning_time_to_collision(self) -> float:
        return self._warning_time_to_collision

    def get_critical_time_to_collision(self) -> float:
        return self._critical_time_to_collision

    # ======================================================
    # GETTERS - ATOMIC OBSERVATIONS
    # ======================================================

    def get_robot_position(self) -> np.ndarray:
        return self._robot_position.copy()

    def get_robot_velocity(self) -> np.ndarray:
        return self._robot_velocity.copy()

    def get_operator_position(self) -> np.ndarray:
        return self._operator_position.copy()

    def get_operator_velocity(self) -> np.ndarray:
        return self._operator_velocity.copy()

    # ======================================================
    # GETTERS - ATOMIC EVALUATION
    # ======================================================

    def get_distance(self) -> float:
        return self._distance

    def get_relative_velocity(self) -> float:
        return self._relative_velocity

    def get_approach_velocity(self) -> float:
        return self._approach_velocity

    def get_time_to_collision(self) -> Optional[float]:
        return self._time_to_collision

    def get_collision_risk_score(self) -> float:
        return self._collision_risk_score

    def get_collision_risk(self) -> str:
        return self._collision_risk

    def is_collision_imminent(self) -> bool:
        return self._collision_imminent

    def is_state_valid(self) -> bool:
        return self._state_valid

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_result(self) -> CollisionResult:
        """
        Return the complete current collision result.
        """

        return CollisionResult(
            distanceb = self._distance,
            relative_velocity = self._relative_velocity,
            approach_velocity = self._approach_velocity,
            time_to_collision = self._time_to_collision,
            collision_risk = self._collision_risk,
            collision_risk_score = self._collision_risk_score,
            collision_imminent = self._collision_imminent
        )

    # ======================================================
    # INTERNAL METHODS
    # ======================================================

    def _calculate_distance(self) -> float:

        distance_vector = self._operator_position - self._robot_position

        return float(np.linalg.norm(distance_vector))

    def _calculate_approach_velocity(self, relative_velocity: np.ndarray) -> float:

        distance_vector = self._operator_position - self._robot_position
        distance = np.linalg.norm(distance_vector)

        if distance <= 0.0:
            return 0.0

        distance_direction = distance_vector / distance

        # Positive value means that the operator and robot
        # are moving toward each other.
        approach_velocity = -np.dot(relative_velocity, distance_direction)

        return max(0.0, float(approach_velocity))

    def _calculate_time_to_collision(self) -> Optional[float]:

        if self._approach_velocity <= 0.0:
            return None

        if self._distance <= 0.0:
            return 0.0

        return self._distance / self._approach_velocity

    def _calculate_collision_risk_score(self) -> float:

        # --------------------------------------------------
        # Distance component
        # --------------------------------------------------

        if self._distance <= self._critical_distance:
            distance_score = 1.0

        elif self._distance >= self._warning_distance:
            distance_score = 0.0

        else:
            distance_score = (self._warning_distance- self._distance) / (self._warning_distance- self._critical_distance)

        # --------------------------------------------------
        # TTC component
        # --------------------------------------------------

        if self._time_to_collision is None:
            ttc_score = 0.0

        elif self._time_to_collision <= self._critical_time_to_collision:
            ttc_score = 1.0

        elif self._time_to_collision >= self._warning_time_to_collision:
            ttc_score = 0.0

        else:
            ttc_score = (self._warning_time_to_collision - self._time_to_collision) / (self._warning_time_to_collision - self._critical_time_to_collision)

        # --------------------------------------------------
        # Combined risk
        # --------------------------------------------------

        risk_score = max(distance_score, ttc_score)

        return max(0.0, min(risk_score, 1.0))

    def _calculate_collision_risk(self) -> str:

        if self._distance <= self._critical_distance:
            return "CRITICAL"

        if self._time_to_collision is not None and self._time_to_collision <= self._critical_time_to_collision:
            return "CRITICAL"

        if self._distance <= self._warning_distance:
            return "WARNING"

        if self._time_to_collision is not None and self._time_to_collision <= self._warning_time_to_collision:
            return "WARNING"

        return "LOW"

    def _calculate_collision_imminent(self) -> bool:

        if self._distance <= self._critical_distance:
            return True

        if self._time_to_collision is None:
            return False

        return self._time_to_collision <= self._critical_time_to_collision

    # ======================================================
    # VALIDATION
    # ======================================================

    @staticmethod
    def _validate_observations(
        robot_position: np.ndarray,
        robot_velocity: np.ndarray,
        operator_position: np.ndarray,
        operator_velocity: np.ndarray) -> None:

        observations = {
            "robot_position": robot_position,
            "robot_velocity": robot_velocity,
            "operator_position": operator_position,
            "operator_velocity": operator_velocity
        }

        for name, value in observations.items():

            if not isinstance(value, np.ndarray):
                raise TypeError(f"{name} must be a numpy array")

            if value.shape != (3,):
                raise ValueError(f"{name} must contain exactly three values")

            if not np.all(np.isfinite(value)):
                raise ValueError(f"{name} contains invalid values")