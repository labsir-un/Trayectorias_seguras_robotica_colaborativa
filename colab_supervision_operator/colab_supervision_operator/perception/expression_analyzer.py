"""
Facial expression analyzer for colab_supervision_operator.

This module contains the domain logic used to analyze facial
expressions previously extracted from the operator's face.
"""

from dataclasses import dataclass
from typing import Optional


@dataclass
class ExpressionResult:
    """
    Complete result generated by ExpressionAnalyzer.
    """

    expression: str
    confidence: float

    is_fatigue_expression: bool
    expression_valid: bool


class ExpressionAnalyzer():
    """
    Analyze operator facial expressions.

    The analyzer receives a facial-expression classification
    and determines whether the detected expression corresponds
    to an expression associated with operator fatigue.

    Expected inputs:

        expression:
            Facial expression detected by the perception model.

        confidence:
            Confidence of the facial-expression classification
            in the range [0.0, 1.0].
    """

    def __init__(self, fatigue_expressions: Optional[set[str]] = None, minimum_confidence: float = 0.50) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._fatigue_expressions = {"tired", "fatigued", "sleepy"}

        if fatigue_expressions is not None:
            self._fatigue_expressions = {
                expression.lower()
                for expression in fatigue_expressions
            }

        self._minimum_confidence = minimum_confidence

        # --------------------------------------------------
        # Current observations
        # --------------------------------------------------

        self._expression = "unknown"
        self._confidence = 0.0

        # --------------------------------------------------
        # Current evaluation
        # --------------------------------------------------

        self._is_fatigue_expression = False
        self._expression_valid = False

    # ======================================================
    # UPDATE
    # ======================================================

    def update(self, expression: str, confidence: float) -> ExpressionResult:
        """
        Update the analyzer with a new facial-expression
        observation.

        Args:
            expression:
                Facial-expression classification.

            confidence:
                Classification confidence [0.0, 1.0].

        Returns:
            Updated ExpressionResult.
        """

        self._validate_observations(expression, confidence)

        self._expression = expression.lower()
        self._confidence = confidence

        # --------------------------------------------------
        # Evaluate expression
        # --------------------------------------------------

        self._expression_valid = self._confidence >= self._minimum_confidence
        self._is_fatigue_expression = self._expression_valid and self._expression in self._fatigue_expressions

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_fatigue_expressions(self, expressions: set[str]) -> None:
        """
        Set the facial expressions considered related to
        operator fatigue.
        """

        if not expressions:
            raise ValueError("fatigue_expressions cannot be empty")

        self._fatigue_expressions = {
            expression.lower()
            for expression in expressions
        }

    def set_minimum_confidence(self, confidence: float) -> None:

        """
        Set the minimum confidence required to accept an
        expression classification.
        """

        self._validate_range(confidence, 0.0, 1.0, "minimum_confidence")
        self._minimum_confidence = confidence

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_fatigue_expressions(self) -> set[str]:
        return self._fatigue_expressions.copy()

    def get_minimum_confidence(self) -> float:
        return self._minimum_confidence

    # ======================================================
    # GETTERS - ATOMIC OBSERVATIONS
    # ======================================================

    def get_expression(self) -> str:
        return self._expression

    def get_confidence(self) -> float:
        return self._confidence

    # ======================================================
    # GETTERS - ATOMIC EVALUATION
    # ======================================================

    def is_fatigue_expression(self) -> bool:
        return self._is_fatigue_expression

    def is_expression_valid(self) -> bool:
        return self._expression_valid

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_result(self) -> ExpressionResult:
        """
        Return the complete current expression result.
        """

        return ExpressionResult(
            expression = self._expression,
            confidence = self._confidence,
            is_fatigue_expression = self._is_fatigue_expression,
            expression_valid = self._expression_valid
        )

    # ======================================================
    # VALIDATION
    # ======================================================

    @staticmethod
    def _validate_range(value: float, minimum: float, maximum: float,name: str) -> None:

        if not minimum <= value <= maximum:
            raise ValueError(f"{name} must be between {minimum} and {maximum}")

    @staticmethod
    def _validate_observations(expression: str, confidence: float) -> None:

        if not isinstance(expression, str):
            raise TypeError("expression must be a string")

        if not expression.strip():
            raise ValueError("expression cannot be empty")

        if not 0.0 <= confidence <= 1.0:
            raise ValueError("confidence must be between 0.0 and 1.0")