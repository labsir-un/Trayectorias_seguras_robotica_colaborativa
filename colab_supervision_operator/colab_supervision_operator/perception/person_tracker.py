"""
Person tracker for colab_supervision_operator.

This module contains the domain logic used to maintain temporal
person detections and tracking information.
"""

from dataclasses import dataclass
from typing import Optional


@dataclass
class PersonDetection:
    """
    Information associated with a detected person.
    """

    track_id: int

    x1: float
    y1: float
    x2: float
    y2: float

    confidence: float

    center_x: float
    center_y: float


@dataclass
class PersonTrackerResult:
    """
    Complete result generated by PersonTracker.
    """

    persons: list[PersonDetection]

    person_detected: bool
    number_of_persons: int

    primary_person_id: Optional[int]


class PersonTracker():
    """
    Track persons detected in consecutive frames.

    The tracker receives person detections generated by an
    external perception model and maintains the current tracking
    information.

    The tracking algorithm itself can be replaced independently
    without changing the interface of this class.
    """

    def __init__(self, confidence_threshold: float = 0.50, maximum_persons: int = 10) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._confidence_threshold = confidence_threshold
        self._maximum_persons = maximum_persons

        # --------------------------------------------------
        # Current observations
        # --------------------------------------------------

        self._persons: list[PersonDetection] = []

        self._person_detected = False
        self._number_of_persons = 0

        self._primary_person_id: Optional[int] = None

    # ======================================================
    # UPDATE
    # ======================================================

    def update(self, detections: list[dict]) -> PersonTrackerResult:
        """
        Update the tracker with new person detections.

        Each detection must contain:

            track_id
            bbox
            confidence

        where bbox is:

            (x1, y1, x2, y2)

        Args:
            detections:
                List of person detections.

        Returns:
            Updated PersonTrackerResult.
        """

        self._validate_detections(detections)
        self._persons = []

        # --------------------------------------------------
        # Process detections
        # --------------------------------------------------

        for detection in detections:

            confidence = detection["confidence"]
            if confidence < self._confidence_threshold:
                continue

            if len(self._persons) >= self._maximum_persons:
                break

            track_id = detection["track_id"]

            x1, y1, x2, y2 = detection["bbox"]

            center_x = (x1 + x2) / 2.0

            center_y = (y1 + y2) / 2.0

            person = PersonDetection(
                track_id=track_id,

                x1=x1,
                y1=y1,
                x2=x2,
                y2=y2,

                confidence=confidence,

                center_x=center_x,
                center_y=center_y
            )

            self._persons.append(person)

        # --------------------------------------------------
        # Update state
        # --------------------------------------------------

        self._number_of_persons = len(self._persons)
        self._person_detected = self._number_of_persons > 0
        self._primary_person_id = self._select_primary_person()

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_confidence_threshold(self, threshold: float) -> None:
        """
        Set the minimum detection confidence.
        """
        self._validate_range(threshold, 0.0, 1.0, "confidence_threshold")
        self._confidence_threshold = threshold

    def set_maximum_persons(self, maximum_persons: int) -> None:
        """
        Set the maximum number of persons to track.
        """
        if maximum_persons <= 0:
            raise ValueError("maximum_persons must be greater than zero")
        self._maximum_persons = maximum_persons

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_confidence_threshold(self) -> float:
        return self._confidence_threshold

    def get_maximum_persons(self) -> int:
        return self._maximum_persons

    # ======================================================
    # GETTERS - ATOMIC OBSERVATIONS
    # ======================================================

    def get_persons(self) -> list[PersonDetection]:
        return self._persons.copy()

    def get_person(self, track_id: int) -> Optional[PersonDetection]:

        for person in self._persons:
            if person.track_id == track_id:
                return person

        return None

    def get_primary_person(self) -> Optional[PersonDetection]:

        if self._primary_person_id is None:
            return None

        return self.get_person(self._primary_person_id)

    def is_person_detected(self) -> bool:
        return self._person_detected

    def get_number_of_persons(self) -> int:
        return self._number_of_persons

    def get_primary_person_id(self) -> Optional[int]:
        return self._primary_person_id

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_result(self) -> PersonTrackerResult:
        """
        Return the complete current tracking result.
        """
        return PersonTrackerResult(
            persons=self._persons.copy(),
            person_detected=self._person_detected,
            number_of_persons=self._number_of_persons,
            primary_person_id=self._primary_person_id
        )

    # ======================================================
    # INTERNAL METHODS
    # ======================================================

    def _select_primary_person(self) -> Optional[int]:
        """
        Select the primary person.

        The current strategy selects the person with the
        highest detection confidence.

        This strategy can later be replaced by a more
        appropriate criterion for the application.
        """

        if not self._persons:
            return None

        primary_person = max(self._persons, key=lambda person: person.confidence)

        return primary_person.track_id

    # ======================================================
    # VALIDATION
    # ======================================================

    @staticmethod
    def _validate_range(value: float, minimum: float, maximum: float, name: str) -> None:

        if not minimum <= value <= maximum:
            raise ValueError(f"{name} must be between {minimum} and {maximum}")

    @staticmethod
    def _validate_detections(detections: list[dict]) -> None:

        if not isinstance(detections, list):
            raise TypeError("detections must be a list")

        for detection in detections:

            if not isinstance(detection, dict):
                raise TypeError("each detection must be a dictionary")

            required_fields = {"track_id", "bbox", "confidence"}

            missing_fields = (required_fields - detection.keys())

            if missing_fields:
                raise ValueError(f"detection is missing fields: {missing_fields}")

            bbox = detection["bbox"]

            if len(bbox) != 4:
                raise ValueError("bbox must contain exactly four values")
            
            confidence = detection["confidence"]

            if not 0.0 <= confidence <= 1.0:
                raise ValueError("confidence must be between 0.0 and 1.0")