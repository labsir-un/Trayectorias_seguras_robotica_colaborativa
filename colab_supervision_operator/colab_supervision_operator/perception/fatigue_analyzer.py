"""
Fatigue analyzer for colab_supervision_operator.

This module contains the domain logic used to evaluate operator
fatigue from previously extracted visual indicators.
"""

from dataclasses import dataclass


@dataclass
class FatigueResult:
    """
    Complete result generated by FatigueAnalyzer.
    """

    eye_openness: float
    blink_frequency: float
    facial_expression: str

    eye_openness_fatigued: bool
    blink_frequency_fatigued: bool
    facial_expression_fatigued: bool

    fatigue_score: float
    fatigue_level: str


class FatigueAnalyzer():
    """
    Analyze operator fatigue from visual indicators.

    The analyzer receives observations from other perception
    modules and evaluates them according to configurable
    thresholds.

    Expected inputs:

        eye_openness:
            Normalized eye openness in the range [0.0, 1.0].

        blink_frequency:
            Blinks per minute.

        facial_expression:
            Facial expression detected by the expression analyzer.
    """

    def __init__(self, eye_openness_threshold: float = 0.30, minimum_blink_frequency: float = 5.0, fatigue_expressions: set[str] = {"tired", "fatigued", "sleepy"}) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._eye_openness_threshold = eye_openness_threshold
        self._minimum_blink_frequency = minimum_blink_frequency
        self._fatigue_expressions = {
                        expression.lower()
                        for expression in fatigue_expressions
                    }

        # --------------------------------------------------
        # Current observations
        # --------------------------------------------------

        self._eye_openness = 0.0
        self._blink_frequency = 0.0
        self._facial_expression = "unknown"

        # --------------------------------------------------
        # Current evaluation
        # --------------------------------------------------

        self._eye_openness_fatigued = False
        self._blink_frequency_fatigued = False
        self._facial_expression_fatigued = False

        self._fatigue_score = 0.0
        self._fatigue_level = "UNKNOWN"

    # ======================================================
    # UPDATE
    # ======================================================

    def update(self, eye_openness: float, blink_frequency: float, facial_expression: str) -> FatigueResult:
        """
        Update the analyzer with new observations.

        Args:
            eye_openness:
                Normalized eye openness [0.0, 1.0].

            blink_frequency:
                Blink frequency in blinks per minute.

            facial_expression:
                Detected facial expression.

        Returns:
            Updated FatigueResult.
        """

        self._validate_observations(eye_openness, blink_frequency, facial_expression)

        self._eye_openness = eye_openness
        self._blink_frequency = blink_frequency
        self._facial_expression = facial_expression

        # --------------------------------------------------
        # Evaluate individual indicators
        # --------------------------------------------------

        self._eye_openness_fatigued = (self._eye_openness < self._eye_openness_threshold)

        self._blink_frequency_fatigued = (self._blink_frequency < self._minimum_blink_frequency)

        self._facial_expression_fatigued = (self._facial_expression.lower() in self._fatigue_expressions)

        # --------------------------------------------------
        # Calculate overall fatigue
        # --------------------------------------------------

        self._fatigue_score = (self._calculate_fatigue_score())

        self._fatigue_level = (self._calculate_fatigue_level())

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_eye_openness_threshold(self, threshold: float) -> None:
        """
        Set the minimum acceptable eye openness.
        """

        self._validate_range(threshold, 0.0, 1.0, "eye_openness_threshold")

        self._eye_openness_threshold = threshold

    def set_minimum_blink_frequency(self, frequency: float) -> None:
        """
        Set the minimum blink frequency in blinks/min.
        """

        if frequency < 0.0:
            raise ValueError(
                "minimum_blink_frequency cannot be negative"
            )

        self._minimum_blink_frequency = frequency

    def set_fatigue_expressions(self, expressions: set[str]) -> None:
        """
        Set the facial expressions considered fatigue-related.
        """

        if not expressions:
            raise ValueError("fatigue_expressions cannot be empty")

        self._fatigue_expressions = {
            expression.lower()
            for expression in expressions
        }

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_eye_openness_threshold(self) -> float:
        return self._eye_openness_threshold

    def get_minimum_blink_frequency(self) -> float:
        return self._minimum_blink_frequency

    def get_fatigue_expressions(self) -> set[str]:
        return self._fatigue_expressions.copy()

    # ======================================================
    # GETTERS - ATOMIC OBSERVATIONS
    # ======================================================

    def get_eye_openness(self) -> float:
        return self._eye_openness

    def get_blink_frequency(self) -> float:
        return self._blink_frequency

    def get_facial_expression(self) -> str:
        return self._facial_expression

    # ======================================================
    # GETTERS - ATOMIC EVALUATION
    # ======================================================

    def is_eye_openness_fatigued(self) -> bool:
        return self._eye_openness_fatigued

    def is_blink_frequency_fatigued(self) -> bool:
        return self._blink_frequency_fatigued

    def is_facial_expression_fatigued(self) -> bool:
        return self._facial_expression_fatigued

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_fatigue_score(self) -> float:
        return self._fatigue_score

    def get_fatigue_level(self) -> str:
        return self._fatigue_level

    def get_result(self) -> FatigueResult:
        """
        Return the complete current fatigue result.
        """

        return FatigueResult(
            eye_openness=self._eye_openness,
            blink_frequency=self._blink_frequency,
            facial_expression=self._facial_expression,
            eye_openness_fatigued=(self._eye_openness_fatigued),
            blink_frequency_fatigued=(self._blink_frequency_fatigued),
            facial_expression_fatigued=(self._facial_expression_fatigued),
            fatigue_score=self._fatigue_score,
            fatigue_level=self._fatigue_level,
        )

    # ======================================================
    # INTERNAL METHODS
    # ======================================================

    def _calculate_fatigue_score(self) -> float:
        """
        Calculate the current fatigue score.

        The current implementation uses the three indicators
        equally. The weighting model can later be calibrated
        experimentally.
        """

        indicators = [
            self._eye_openness_fatigued,
            self._blink_frequency_fatigued,
        ]

        score = sum(indicators) / len(indicators)

        return score

    def _calculate_fatigue_level(self) -> str:
        """
        Convert fatigue score into a qualitative level.
        """

        if self._fatigue_score == 0.0:
            return "LOW"

        if self._fatigue_score < 0.50:
            return "MEDIUM"

        return "HIGH"

    @staticmethod
    def _validate_range(value: float, minimum: float, maximum: float, name: str) -> None:

        if not minimum <= value <= maximum:
            raise ValueError(
                f"{name} must be between "
                f"{minimum} and {maximum}"
            )

    @staticmethod
    def _validate_observations(eye_openness: float, blink_frequency: float,facial_expression: str) -> None:

        if not 0.0 <= eye_openness <= 1.0:
            raise ValueError("eye_openness must be between 0.0 and 1.0")

        if blink_frequency < 0.0:
            raise ValueError("blink_frequency cannot be negative")

        if not isinstance(facial_expression, str):
            raise TypeError("facial_expression must be a string")