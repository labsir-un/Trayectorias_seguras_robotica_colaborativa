"""
Robot state module for colab_supervision_operator.

This module contains the domain logic used to store and provide
the current robot state required for robot-operator interaction
analysis.
"""

from dataclasses import dataclass
from typing import Optional

import numpy as np


@dataclass
class RobotStateResult:
    """
    Complete result generated by RobotState.
    """

    joint_positions: np.ndarray
    joint_velocities: np.ndarray

    tcp_position: Optional[np.ndarray]
    tcp_orientation: Optional[np.ndarray]

    tcp_linear_velocity: Optional[np.ndarray]
    tcp_angular_velocity: Optional[np.ndarray]

    state_valid: bool


class RobotState():
    """
    Store and provide the current robot state.

    The class stores joint positions and velocities and optionally
    the Cartesian state of the robot TCP.

    ROS 2 communication is intentionally handled outside this
    class.

    Expected inputs:

        joint_positions:
            Joint positions in radians.

        joint_velocities:
            Joint velocities in radians per second.

        tcp_position:
            TCP position [x, y, z] in meters.

        tcp_orientation:
            TCP orientation represented as a quaternion
            [x, y, z, w].

        tcp_linear_velocity:
            TCP linear velocity [vx, vy, vz] in meters per second.

        tcp_angular_velocity:
            TCP angular velocity [wx, wy, wz] in radians per second.
    """

    def __init__(self, number_of_joints: int = 6) -> None:

        # --------------------------------------------------
        # Configuration parameters
        # --------------------------------------------------

        self._number_of_joints = number_of_joints

        # --------------------------------------------------
        # Current joint state
        # --------------------------------------------------

        self._joint_positions = np.zeros(self._number_of_joints, dtype=float)
        self._joint_velocities = np.zeros(self._number_of_joints, dtype=float)

        # --------------------------------------------------
        # Current Cartesian state
        # --------------------------------------------------

        self._tcp_position: Optional[np.ndarray] = None
        self._tcp_orientation: Optional[np.ndarray] = None
        self._tcp_linear_velocity: Optional[np.ndarray] = None
        self._tcp_angular_velocity: Optional[np.ndarray] = None

        # --------------------------------------------------
        # State
        # --------------------------------------------------

        self._state_valid = False

    # ======================================================
    # UPDATE - JOINT STATE
    # ======================================================

    def update_joint_state(self, joint_positions: np.ndarray, joint_velocities: np.ndarray) -> RobotStateResult:
        """
        Update the robot joint state.

        Args:
            joint_positions:
                Joint positions in radians.

            joint_velocities:
                Joint velocities in radians per second.

        Returns:
            Updated RobotStateResult.
        """

        self._validate_joint_state(joint_positions,joint_velocities)
        self._joint_positions = np.asarray(joint_positions, dtype=float).copy()
        self._joint_velocities = np.asarray(joint_velocities, dtype=float).copy()
        self._state_valid = True

        return self.get_result()

    # ======================================================
    # UPDATE - CARTESIAN STATE
    # ======================================================

    def update_tcp_state(self,
        tcp_position: np.ndarray,
        tcp_orientation: np.ndarray,
        tcp_linear_velocity: Optional[np.ndarray] = None,
        tcp_angular_velocity: Optional[np.ndarray] = None) -> RobotStateResult:
        """
        Update the Cartesian state of the robot TCP.

        Args:
            tcp_position:
                TCP position [x, y, z] in meters.

            tcp_orientation:
                TCP quaternion [x, y, z, w].

            tcp_linear_velocity:
                TCP linear velocity [vx, vy, vz] in m/s.

            tcp_angular_velocity:
                TCP angular velocity [wx, wy, wz] in rad/s.

        Returns:
            Updated RobotStateResult.
        """
        self._validate_tcp_state(
            tcp_position,
            tcp_orientation,
            tcp_linear_velocity,
            tcp_angular_velocity
        )

        self._tcp_position = np.asarray(tcp_position, dtype=float).copy()
        self._tcp_orientation = np.asarray(tcp_orientation, dtype=float).copy()

        if tcp_linear_velocity is not None:
            self._tcp_linear_velocity = np.asarray(tcp_linear_velocity, dtype=float).copy()

        if tcp_angular_velocity is not None:
            self._tcp_angular_velocity = np.asarray(tcp_angular_velocity, dtype=float).copy()

        return self.get_result()

    # ======================================================
    # SETTERS - CONFIGURATION
    # ======================================================

    def set_number_of_joints(self,number_of_joints: int) -> None:
        """
        Set the number of robot joints.

        Changing the number of joints resets the stored joint
        state.
        """

        if number_of_joints <= 0:
            raise ValueError("number_of_joints must be greater than zero")

        self._number_of_joints = number_of_joints
        self._joint_positions = np.zeros(self._number_of_joints, dtype=float)

        self._joint_velocities = np.zeros(self._number_of_joints, dtype=float)

        self._state_valid = False

    # ======================================================
    # GETTERS - CONFIGURATION
    # ======================================================

    def get_number_of_joints(self) -> int:
        return self._number_of_joints

    # ======================================================
    # GETTERS - JOINT STATE
    # ======================================================

    def get_joint_positions(self) -> np.ndarray:
        return self._joint_positions.copy()

    def get_joint_velocities(self) -> np.ndarray:
        return self._joint_velocities.copy()

    # ======================================================
    # GETTERS - CARTESIAN STATE
    # ======================================================

    def get_tcp_position(self) -> Optional[np.ndarray]:

        if self._tcp_position is None:
            return None

        return self._tcp_position.copy()

    def get_tcp_orientation(self) -> Optional[np.ndarray]:

        if self._tcp_orientation is None:
            return None

        return self._tcp_orientation.copy()

    def get_tcp_linear_velocity(self) -> Optional[np.ndarray]:

        if self._tcp_linear_velocity is None:
            return None

        return self._tcp_linear_velocity.copy()

    def get_tcp_angular_velocity(self) -> Optional[np.ndarray]:

        if self._tcp_angular_velocity is None:
            return None

        return self._tcp_angular_velocity.copy()

    # ======================================================
    # GETTERS - STATE
    # ======================================================

    def is_state_valid(self) -> bool:

        return self._state_valid

    # ======================================================
    # GETTERS - RESULT
    # ======================================================

    def get_result(self) -> RobotStateResult:
        """
        Return the complete current robot state.
        """

        return RobotStateResult(

            joint_positions=self._joint_positions.copy(),
            joint_velocities=self._joint_velocities.copy(),
            tcp_position= None if self._tcp_position is None else self._tcp_position.copy(),
            tcp_orientation= None if self._tcp_orientation is None else self._tcp_orientation.copy(),
            tcp_linear_velocity= None if self._tcp_linear_velocity is None else self._tcp_linear_velocity.copy(),
            tcp_angular_velocity= None if self._tcp_angular_velocity is None else self._tcp_angular_velocity.copy(),
            state_valid=self._state_valid
        )

    # ======================================================
    # VALIDATION
    # ======================================================

    def _validate_joint_state(self, joint_positions: np.ndarray, joint_velocities: np.ndarray) -> None:

        if not isinstance(joint_positions, np.ndarray):
            raise TypeError("joint_positions must be a numpy array")

        if not isinstance(joint_velocities, np.ndarray):
            raise TypeError("joint_velocities must be a numpy array")

        if joint_positions.shape != (self._number_of_joints,):
            raise ValueError(f"joint_positions must contain {self._number_of_joints} values")

        if joint_velocities.shape != (self._number_of_joints):
            raise ValueError(f"joint_velocities must contain {self._number_of_joints} values")

        if not np.all(np.isfinite(joint_positions)):
            raise ValueError("joint_positions contains invalid values")

        if not np.all(np.isfinite(joint_velocities)):
            raise ValueError("joint_velocities contains invalid values")

    @staticmethod
    def _validate_tcp_state(
        tcp_position: np.ndarray,
        tcp_orientation: np.ndarray,
        tcp_linear_velocity: Optional[np.ndarray],
        tcp_angular_velocity: Optional[np.ndarray]) -> None:

        if not isinstance(tcp_position, np.ndarray):
            raise TypeError("tcp_position must be a numpy array")

        if tcp_position.shape != (3,):
            raise ValueError("tcp_position must contain exactly three values")

        if not isinstance(tcp_orientation, np.ndarray):
            raise TypeError("tcp_orientation must be a numpy array")

        if tcp_orientation.shape != (4,):
            raise ValueError("tcp_orientation must contain exactly four values [x, y, z, w]")

        if not np.all(np.isfinite(tcp_position)):
            raise ValueError("tcp_position contains invalid values")

        if not np.all(np.isfinite(tcp_orientation)):
            raise ValueError("tcp_orientation contains invalid values")

        if tcp_linear_velocity is not None:

            if not isinstance(tcp_linear_velocity, np.ndarray):
                raise TypeError("tcp_linear_velocity must be a numpy array")

            if tcp_linear_velocity.shape != (3,):
                raise ValueError("tcp_linear_velocity must contain exactly three values")

            if not np.all(np.isfinite(tcp_linear_velocity)):
                raise ValueError("tcp_linear_velocity contains invalid values")

        if tcp_angular_velocity is not None:

            if not isinstance(tcp_angular_velocity, np.ndarray):
                raise TypeError("tcp_angular_velocity must be a numpy array")

            if tcp_angular_velocity.shape != (3,):
                raise ValueError("tcp_angular_velocity must contain exactly three values")

            if not np.all(np.isfinite(tcp_angular_velocity)):
                raise ValueError("tcp_angular_velocity containsinvalid values")